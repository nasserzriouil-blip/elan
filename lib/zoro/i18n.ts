const DATE_LOCALE: Record<Lang, string> = { fr: "fr-FR", en: "en-GB", ar: "ar-MA" };

export function fmtDate(lang: Lang, iso: string, opts: Intl.DateTimeFormatOptions = { weekday: "short", day: "numeric", month: "short" }): string {
  if (!iso) return "—";
  try {
    return new Intl.DateTimeFormat(DATE_LOCALE[lang], { ...opts, numberingSystem: "latn" }).format(new Date(iso + "T12:00:00"));
  } catch {
    return iso;
  }
}

export function fmtDateLong(lang: Lang, iso: string): string {
  return fmtDate(lang, iso, { weekday: "long", day: "numeric", month: "long", year: "numeric" });
}
